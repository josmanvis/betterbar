import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { test, expect, installRuntime, seed } from "./fixtures";
const sourcePath = fileURLToPath(new URL("../../extensions/focus-timer/main.tsx", import.meta.url));
const source = existsSync(sourcePath) ? readFileSync(sourcePath, "utf8") : "";
test.skip(!source, "Requires the local Focus Timer extension.");
const registryExtensions = [{ name: "focus-timer", display_name: "Focus Timer", content: source }];
test("Pomodoro icon synchronizes to the bar and persists without resetting a running session", async ({ page, context }, testInfo) => {
  const config = { ...seed, enabledExtensions: ["focus-timer"] };
  await installRuntime(page, { registryExtensions, config });
  await page.goto("/");
  const timer = await context.newPage();
  await installRuntime(timer, { label: "ext_focus_timer", registryExtensions, config });
  await timer.goto("/?ext=focus-timer");
  await timer.getByRole("button", { name: "Start", exact: true }).click();
  const savedTimer = await timer.evaluate(() => localStorage.getItem("bb-focus-timer-state"));
  const bar = await context.newPage();
  await installRuntime(bar, { label: "main", registryExtensions, config });
  await bar.goto("/");
  await expect(bar.locator('[data-focus-icon="clock"]')).toBeVisible();
  await page.getByRole("tab", { name: "Extensions", exact: true }).click();
  await page.getByRole("button", { name: "Configure Focus Timer", exact: true }).click();
  await page.getByRole("button", { name: "Pomodoro", exact: true }).click();
  await expect(page.getByRole("button", { name: "Pomodoro", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(bar.locator('[data-focus-icon="pomodoro"]')).toBeVisible();
  expect(await timer.evaluate(() => localStorage.getItem("bb-focus-timer-state"))).toBe(savedTimer);
  await bar.reload();
  await expect(bar.locator('[data-focus-icon="pomodoro"]')).toBeVisible();
  await expect(timer.getByRole("button", { name: "Pause", exact: true })).toBeVisible();
  await testInfo.attach("pomodoro-icon-options.png", { body: await page.screenshot(), contentType: "image/png" });
  expect(await timer.evaluate(() => (window as any).__unexpectedIPC)).toEqual([]);
  expect(await bar.evaluate(() => (window as any).__unexpectedIPC)).toEqual([]);
  await bar.close(); await timer.close();
});
